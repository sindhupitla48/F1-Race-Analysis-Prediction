import os
import glob
import numpy as np
import pandas as pd
import plotly.express as px
from IPython.display import display

# ------------------------------------------------------------
# 1. Load existing data
# ------------------------------------------------------------

FOLDER = "/content/F1_RETRY_DATA/ANALYSIS_OUTPUT"
CACHE_FOLDER = os.path.join(FOLDER, "weather_cache")

weather_files = glob.glob(
    os.path.join(CACHE_FOLDER, "*_weather.csv")
)

if not weather_files:
    raise FileNotFoundError("No cached weather files found.")

weather = pd.concat(
    [pd.read_csv(f) for f in weather_files],
    ignore_index=True
)

locations_file = os.path.join(
    FOLDER, "f1_race_calendar_locations.csv"
)

locations = pd.read_csv(locations_file)

# ------------------------------------------------------------
# 2. Standardize dates and numeric fields
# ------------------------------------------------------------

weather["date"] = pd.to_datetime(
    weather["date"], errors="coerce"
)

locations["race_date"] = pd.to_datetime(
    locations["race_date"], errors="coerce"
)

weather["temperature_2m_max"] = pd.to_numeric(
    weather["temperature_2m_max"], errors="coerce"
)

weather["temperature_2m_mean"] = pd.to_numeric(
    weather["temperature_2m_mean"], errors="coerce"
)

weather["temperature_2m_min"] = pd.to_numeric(
    weather["temperature_2m_min"], errors="coerce"
)

weather = weather.dropna(
    subset=["date", "temperature_2m_max"]
).copy()

# Remove accidental duplicate circuit/date observations
weather = weather.drop_duplicates(
    subset=["circuit_id", "date"]
)

# ------------------------------------------------------------
# 3. Define unusually hot days using a local historical baseline
# ------------------------------------------------------------
# A hot day = maximum temperature above the 90th percentile
# for the same circuit and calendar day-of-year, using
# a +/- 15-day seasonal window across available years.
#
# This is a local historical threshold, not a universal
# heat-health warning threshold.

weather["day_of_year"] = weather["date"].dt.dayofyear

def seasonal_threshold(group):
    group = group.copy()
    dates = group["day_of_year"].to_numpy()
    temps = group["temperature_2m_max"].to_numpy()

    thresholds = []

    for day in dates:
        # Account approximately for the year boundary
        distance = np.abs(dates - day)
        distance = np.minimum(distance, 366 - distance)

        baseline = temps[distance <= 15]

        if len(baseline) >= 100:
            thresholds.append(np.nanpercentile(baseline, 90))
        else:
            thresholds.append(np.nan)

    group["hot_day_threshold_c"] = thresholds
    return group

weather = (
    weather.groupby("circuit_id", group_keys=False)
    .apply(seasonal_threshold)
    .reset_index(drop=True)
)

weather["unusually_hot_day"] = (
    weather["temperature_2m_max"]
    > weather["hot_day_threshold_c"]
)

# A heatwave is at least 3 consecutive unusually hot days.
weather = weather.sort_values(["circuit_id", "date"]).copy()

weather["previous_date"] = (
    weather.groupby("circuit_id")["date"].shift(1)
)

weather["consecutive_hot"] = (
    weather["unusually_hot_day"]
    & weather["previous_date"].notna()
    & (
        (weather["date"] - weather["previous_date"]).dt.days == 1
    )
)

# Identify runs of consecutive hot days
weather["run_group"] = (
    weather.groupby("circuit_id")["consecutive_hot"]
    .transform(lambda s: (~s).cumsum())
)

weather["hot_run_length"] = (
    weather.groupby(["circuit_id", "run_group"])
    ["unusually_hot_day"]
    .transform("sum")
)

weather["heatwave_day"] = (
    weather["unusually_hot_day"]
    & (weather["hot_run_length"] >= 3)
)

