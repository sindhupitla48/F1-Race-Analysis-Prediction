import os
import numpy as np
import pandas as pd
import plotly.express as px

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.ensemble import RandomForestRegressor
from sklearn.dummy import DummyRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

# ------------------------------------------------------------
# 1. Load dataset
# ------------------------------------------------------------

folder = "/content/F1_RETRY_DATA/ANALYSIS_OUTPUT"

df = pd.read_csv(
    os.path.join(folder, "clean_race_results.csv")
)

# ------------------------------------------------------------
# 2. Clean data
# ------------------------------------------------------------

for col in ["season", "round", "grid", "position"]:
    df[col] = pd.to_numeric(df[col], errors="coerce")

df["race_date"] = pd.to_datetime(
    df["race_date"], errors="coerce"
)

# Keep only numeric, classified finishing positions
df = df.dropna(
    subset=[
        "season", "round", "grid", "position",
        "driver_name", "constructor_name", "race_name"
    ]
).copy()

df = df[
    (df["position"] >= 1)
    & (df["grid"] >= 1)
].copy()

df["season"] = df["season"].astype(int)
df["round"] = df["round"].astype(int)

# ------------------------------------------------------------
# 3. Create pre-race features
# ------------------------------------------------------------
# No points, final position, status, laps or race time as inputs.

feature_columns = [
    "grid",
    "season",
    "round",
    "driver_name",
    "constructor_name",
    "race_name"
]

target = "position"

train = df[df["season"] <= 2022].copy()
test = df[df["season"].isin([2023, 2024])].copy()

if train.empty or test.empty:
    raise ValueError("Training or testing data is empty.")

X_train = train[feature_columns]
y_train = train[target]

X_test = test[feature_columns]
y_test = test[target]

categorical_features = [
    "driver_name", "constructor_name", "race_name"
]

numeric_features = ["grid", "season", "round"]

preprocessor = ColumnTransformer(
    transformers=[
        (
            "numeric",
            Pipeline([
                ("imputer", SimpleImputer(strategy="median"))
            ]),
            numeric_features
        ),
        (
            "categorical",
            Pipeline([
                ("imputer", SimpleImputer(strategy="most_frequent")),
                (
                    "onehot",
                    OneHotEncoder(handle_unknown="ignore")
                )
            ]),
            categorical_features
        )
    ]
)

# ------------------------------------------------------------
# 4. Baseline model
# ------------------------------------------------------------

baseline = DummyRegressor(strategy="median")
baseline.fit(X_train[["grid"]], y_train)

baseline_predictions = baseline.predict(X_test[["grid"]])

# ------------------------------------------------------------
# 5. Random Forest model
# ------------------------------------------------------------

model = Pipeline([
    ("preprocessor", preprocessor),
    (
        "model",
        RandomForestRegressor(
            n_estimators=250,
            min_samples_leaf=3,
            random_state=42,
            n_jobs=-1
        )
    )
])

model.fit(X_train, y_train)

predictions = model.predict(X_test)

# ------------------------------------------------------------
# 6. Evaluate both models
# ------------------------------------------------------------

results = pd.DataFrame([
    {
        "Model": "Median baseline",
        "MAE": mean_absolute_error(y_test, baseline_predictions),
        "RMSE": np.sqrt(
            mean_squared_error(y_test, baseline_predictions)
        ),
        "R2": r2_score(y_test, baseline_predictions)
    },
    {
        "Model": "Random Forest",
        "MAE": mean_absolute_error(y_test, predictions),
        "RMSE": np.sqrt(
            mean_squared_error(y_test, predictions)
        ),
        "R2": r2_score(y_test, predictions)
    }
])

print("Training seasons: 2010–2022")
print("Testing seasons: 2023–2024")
print("Training records:", len(X_train))
print("Testing records:", len(X_test))
print("\nModel evaluation:")
display(results.round(3))

