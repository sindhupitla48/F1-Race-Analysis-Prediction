def fetch_all_pages(year, endpoint):
    """Fetch every paginated record for one season and endpoint."""
    limit = 100
    offset = 0
    records = []
    expected_total = None

    while True:
        url = f"{BASE}/{year}/{endpoint}.json"

        response = session.get(
            url,
            params={"limit": limit, "offset": offset},
            timeout=60
        )
        response.raise_for_status()

        mrdata = response.json()["MRData"]

        if expected_total is None:
            expected_total = int(mrdata["total"])
            print(f"  {endpoint}: API total = {expected_total}")

        races = mrdata["RaceTable"]["Races"]
        page_records = 0

        for race in races:
            if endpoint == "results":
                items = race.get("Results", [])
            else:
                items = race.get("QualifyingResults", [])

            for item in items:
                driver = item.get("Driver", {})
                constructor = item.get("Constructor", {})

                row = {
                    "season": int(race.get("season", year)),
                    "round": int(race["round"]),
                    "race_name": race.get("raceName"),
                    "race_date": race.get("date"),
                    "driver_id": driver.get("driverId"),
                    "driver_name": (
                        driver.get("givenName", "") + " " +
                        driver.get("familyName", "")
                    ).strip(),
                    "constructor_id": constructor.get("constructorId"),
                    "constructor_name": constructor.get("name")
                }

                if endpoint == "results":
                    row.update({
                        "grid": item.get("grid"),
                        "position": item.get("position"),
                        "position_text": item.get("positionText"),
                        "points": item.get("points"),
                        "laps": item.get("laps"),
                        "status": item.get("status"),
                        "race_time": item.get("Time", {}).get("time"),
                        "milliseconds": item.get("Time", {}).get("millis")
                    })
                else:
                    row.update({
                        "qualifying_position": item.get("position"),
                        "q1": item.get("Q1"),
                        "q2": item.get("Q2"),
                        "q3": item.get("Q3")
                    })

                records.append(row)
                page_records += 1

        print(
            f"    offset={offset}: "
            f"{page_records} records; collected={len(records)}"
        )

        # Stop only when all reported records have been retrieved,
        # or when the API returns no further records.
        if len(records) >= expected_total or page_records == 0:
            break

        offset += limit
        time.sleep(1)

    if expected_total is not None and len(records) != expected_total:
        print(
            f"  WARNING: API reported {expected_total}, "
            f"but collected {len(records)} records."
        )

    return records, expected_total


