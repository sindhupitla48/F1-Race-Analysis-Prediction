def fetch_standings(year, endpoint):
    url = f"{API}/{year}/{endpoint}.json"
    response = requests.get(url, timeout=30)
    response.raise_for_status()
    data = response.json()["MRData"]["StandingsTable"]
    lists = data.get("StandingsLists", [])

    if not lists:
        return []

    rows = []

    if endpoint == "driverStandings":
        items = lists[0].get("DriverStandings", [])
        for item in items:
            driver = item["Driver"]
            constructors = item.get("Constructors", [])
            rows.append({
                "season": year,
                "position": int(item["position"]),
                "driver_id": driver["driverId"],
                "driver_name": (
                    driver["givenName"] + " " + driver["familyName"]
                ),
                "constructor_names": ", ".join(
                    c["name"] for c in constructors
                ),
                "points": float(item["points"]),
                "wins": int(item["wins"])
            })

    else:
        items = lists[0].get("ConstructorStandings", [])
        for item in items:
            constructor = item["Constructor"]
            rows.append({
                "season": year,
                "position": int(item["position"]),
                "constructor_id": constructor["constructorId"],
                "constructor_name": constructor["name"],
                "points": float(item["points"]),
                "wins": int(item["wins"])
            })

    return rows


